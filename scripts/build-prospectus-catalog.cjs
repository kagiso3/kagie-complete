// Build the institution-only view of the existing national catalogue.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = vm.createContext({window: {}, console});
const assets = JSON.parse(fs.readFileSync(path.join(__dirname, 'prospectus-assets.json'), 'utf8'));
for (const file of ['js/data.js', 'js/sa-catalog.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context);
}
const institutions = context.window.KagieData.institutions.map(item => {
  const record = {...item};
  // The existing API derives current status from dates and manual status.
  delete record.status;
  const asset = assets[record.id];
  if (asset) {
    record.website = record.website || asset.website;
    record.logo = record.logo || asset.logo;
  }
  return record;
});
const output = '// Generated by scripts/build-prospectus-catalog.cjs from the existing national catalogue.\n' +
  '(function () {\n  "use strict";\n  window.KagieData = {...window.KagieData, institutions: ' +
  JSON.stringify(institutions) + '};\n})();\n';
fs.writeFileSync(path.join(root, 'js/prospectus-catalog.js'), output);
console.log(`${institutions.length} institutions; ${Buffer.byteLength(output)} bytes (school records omitted).`);
